import { chromium } from '@playwright/test'

const browser = await chromium.launch({ channel: 'chrome', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 })
const errors = []
page.on('console', (message) => {
  if (message.type() === 'error') errors.push(message.text())
})
page.on('pageerror', (error) => errors.push(error.message))
await page.goto('http://127.0.0.1:5175/', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(2500)
await page.screenshot({ path: 'artifacts/home.png', fullPage: false })
await page.goto('http://127.0.0.1:5175/walkthrough', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(3000)
await page.screenshot({ path: 'artifacts/walkthrough.png', fullPage: false })
await page.mouse.wheel(0, 2200)
await page.waitForTimeout(1200)
await page.screenshot({ path: 'artifacts/walkthrough-scroll.png', fullPage: false })
await page.evaluate(() => document.getElementById('attention')?.scrollIntoView())
await page.waitForTimeout(1600)
await page.screenshot({ path: 'artifacts/walkthrough-attention.png', fullPage: false })
await page.goto('http://127.0.0.1:5175/lab/attention', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(2200)
await page.screenshot({ path: 'artifacts/lab-attention.png', fullPage: false })
await page.goto('http://127.0.0.1:5175/lab/kv-cache', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(900)
await page.screenshot({ path: 'artifacts/lab-kv.png', fullPage: false })
await page.goto('http://127.0.0.1:5175/lab/sampling', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(2200)
await page.getByRole('button', { name: '生成 24 个字符' }).click()
await page.waitForTimeout(3500)
await page.screenshot({ path: 'artifacts/lab-sampling.png', fullPage: false })
const generated = await page.locator('.generated-text').innerText()
await page.goto('http://127.0.0.1:5175/about', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(2200)
await page.screenshot({ path: 'artifacts/about.png', fullPage: false })
const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 })
mobile.on('console', (message) => {
  if (message.type() === 'error') errors.push(`mobile: ${message.text()}`)
})
await mobile.goto('http://127.0.0.1:5175/', { waitUntil: 'domcontentloaded' })
await mobile.waitForTimeout(2500)
await mobile.screenshot({ path: 'artifacts/mobile-home.png', fullPage: false })
await mobile.goto('http://127.0.0.1:5175/walkthrough', { waitUntil: 'domcontentloaded' })
await mobile.waitForTimeout(2500)
await mobile.screenshot({ path: 'artifacts/mobile-walkthrough.png', fullPage: false })
console.log(JSON.stringify({ errors, title: await page.title(), generated }, null, 2))
await browser.close()
